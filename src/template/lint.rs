    // One test per rule.

    #[test]
    fn a_url_that_does_not_parse_is_a_malformed_url_error() {
        for href in [
            "https://",
            "https://a.example:99999/",
            "http://exa_m%ple.com:x/",
        ] {
            let f = one(&button(href));
            assert_eq!(f.rule, Rule::MalformedUrl, "{href}: {f:?}");
            assert_eq!(f.severity, Severity::Error);
            assert!(f.message.contains(href), "{f:?}");
        }
        // A relative URL is not malformed: it names no scheme to refuse and M2c's unsubscribe
        // links are written that way.
        for href in ["/u/unsub", "unsub.html", "?x=1"] {
            assert_eq!(run("", Some(&button(href))), vec![], "{href}");
        }
    }

    #[test]
    fn a_scheme_outside_the_allowlist_is_an_unsupported_scheme_error() {
        for href in [
            "javascript:alert(1)",
            "data:text/html,<b>",
            "ftp://a.example/x",
        ] {
            let f = one(&button(href));
            assert_eq!(f.rule, Rule::UnsupportedScheme, "{href}: {f:?}");
            assert_eq!(f.severity, Severity::Error);
        }
        // The frozen allowlist, each one accepted.
        for href in [
            "https://a.example/x",
            "http://a.example/x",
            "mailto:a@b.example",
            "tel:+15550100",
        ] {
            assert_eq!(run("", Some(&button(href))), vec![], "{href}");
        }
    }

    #[test]
    fn an_empty_url_field_is_an_empty_href_warning() {
        for href in ["", "   ", "\t\n"] {
            let f = one(&link(href));
            assert_eq!(f.rule, Rule::EmptyHref, "{href:?}: {f:?}");
            assert_eq!(f.severity, Severity::Warning);
        }
    }

    #[test]
    fn a_merge_tag_in_a_url_is_a_tag_in_link_position_warning() {
        let f = one(&button("https://app.example/u/{{ token }}"));
        assert_eq!(f.rule, Rule::TagInLinkPosition);
        assert_eq!(f.severity, Severity::Warning);
        // It says it could not be checked, NOT that it is wrong: contract section 13 makes a
        // per-recipient link the ordinary case, and an error here trains operators to ignore
        // the panel.
        let m = f.message.to_lowercase();
        assert!(m.contains("could not"), "{f:?}");
        for wrong in ["invalid", "not allowed", "remove"] {
            assert!(!m.contains(wrong), "{f:?}");
        }
        // And it is the only finding: the rest of the URL is not re-checked as literal text.
        assert_eq!(run("", Some(&button("{{ unsubscribe_url }}"))).len(), 1);
    }

    #[test]
    fn a_mailto_without_an_address_is_an_error() {
        for href in ["mailto:", "mailto:?subject=hi"] {
            let f = one(&link(href));
            assert_eq!(f.rule, Rule::MailtoWithoutAddress, "{href}: {f:?}");
            assert_eq!(f.severity, Severity::Error);
        }
        assert_eq!(
            run("", Some(&link("mailto:a@b.example?subject=hi"))),
            vec![]
        );
        // The rule is about `mailto:` and nothing else. Another allowed scheme can have an empty
        // path without a recipient having anywhere to write to.
        assert_eq!(run("", Some(&link("tel:"))), vec![]);
    }

    #[test]
    fn an_unencoded_space_is_a_warning() {
        let f = one(&button("https://a.example/my file.pdf"));
        assert_eq!(f.rule, Rule::UnencodedSpace);
        assert_eq!(f.severity, Severity::Warning);
        // A space the URL parser cannot fix either: `tel:` keeps it verbatim.
        assert_eq!(one(&link("tel:+1 555 0100")).rule, Rule::UnencodedSpace);
        // A tab or a newline INSIDE a URL is worse than a space, not better: the URL parser
        // deletes it silently, so the address a recipient reaches is not the one on the screen.
        for href in ["https://a.example/a\tb", "https://a.example/a\nb"] {
            let f = one(&button(href));
            assert_eq!(f.rule, Rule::UnencodedSpace, "{href:?}: {f:?}");
        }
        assert_eq!(
            super::check_static_url("https://a.example/a\tb"),
            super::check_static_url("https://a.example/ab"),
            "the tab is deleted, which is why it is worth a finding"
        );
        // Surrounding whitespace is not a finding: the URL parser strips it.
        assert_eq!(run("", Some(&button(" https://a.example/x "))), vec![]);
        // Percent-encoded, which is what the message asks for.
        assert_eq!(
            run("", Some(&button("https://a.example/my%20file.pdf"))),
            vec![]
        );
    }

    #[test]
    fn an_at_rule_inside_an_inline_style_is_a_warning() {
        let src = head(
            "<mj-style inline=\"inline\">.b { color: red; } \
             @media (prefers-color-scheme: dark) { .b { color: white; } }</mj-style>",
        );
        let f = run(&src, None);
        assert_eq!(f.len(), 1, "{f:?}");
        assert_eq!(f[0].rule, Rule::AtRuleInInlineStyle);
        assert_eq!(f[0].severity, Severity::Warning);
        assert_eq!(f[0].check, Check::Lint);
        assert_eq!(f[0].at, None);
        assert!(f[0].message.contains("@media"), "{:?}", f[0]);

        // Written from the RENDERED output, not from a belief about mrml: the rule the operator
        // wrote is nowhere in the document mrml produces, with no error and no warning.
        let html = render(&src);
        assert!(!html.contains("prefers-color-scheme"), "{html}");
        // The non-at-rule part of the same block DID survive, as a style attribute. That is what
        // makes the loss silent: the operator sees their inline styles working.
        assert!(html.contains("color: red"), "{html}");

        // The same at-rule in a style tag that is not inlined is kept, and is not a finding.
        let kept = head(
            "<mj-style>@media (prefers-color-scheme: dark) { .b { color: white; } }</mj-style>",
        );
        assert_eq!(run(&kept, None), vec![]);
        assert!(render(&kept).contains("prefers-color-scheme"));

        // An `@` that does not start a rule is not an at-rule.
        let not = head("<mj-style inline=\"inline\">.b { content: \"a@b\"; }</mj-style>");
        assert_eq!(run(&not, None), vec![]);
    }

    #[test]
    fn an_inline_value_other_than_inline_is_a_warning() {
        for value in ["true", "yes", "Inline", "inline ", ""] {
            let src = head(&format!(
                "<mj-style inline=\"{value}\">.t {{ color: blue; }}</mj-style>"
            ));
            let f = run(&src, None);
            assert_eq!(f.len(), 1, "{value:?}: {f:?}");
            assert_eq!(f[0].rule, Rule::MisspelledInlineAttribute, "{value:?}");
            assert_eq!(f[0].severity, Severity::Warning);

            // Again from the rendered output: the styles were NOT inlined, and nothing said so.
            let html = render(&src);
            assert!(html.contains("<style"), "{html}");
            assert!(!html.contains("color: blue;font-size"), "{html}");
        }
        assert_eq!(
            run(
                &head("<mj-style inline=\"inline\">.t { color: blue; }</mj-style>"),
                None
            ),
            vec![]
        );
    }

    /// By construction, not by watching a quiet run: a run that happens to be quiet proves
    /// nothing about the next one, and resolving an operator's URL is request forgery.
    #[test]
    fn lint_makes_no_network_call() {
        let src = include_str!("lint.rs");
        let (code, _) = src
            .split_once("#[cfg(test)]")
            .expect("the tests sit at the end of this file");
        for name in [
            "reqwest",
            "hyper",
            "hickory",
            "lettre",
            "TcpStream",
            "UdpSocket",
            "std::net",
            "tokio::net",
            "lookup_host",
            "async ",
            ".await",
        ] {
            assert!(!code.contains(name), "the checker can reach {name}");
        }
        // Everything it imports is this crate's own code: there is no client here to call.
        for line in code.lines().filter(|l| l.starts_with("use ")) {
            assert!(
                line.starts_with("use super::")
                    || line.starts_with("use serde")
                    || line.starts_with("use utoipa"),
                "unexpected import: {line}"
            );
        }
        // The one external crate it names is `mrml`, whose six loader features are what would
        // make IT fetch. They are denied in the manifest, and this pins that.
        let manifest = include_str!("../../Cargo.toml");
        let dep = manifest
            .lines()
            .find(|l| l.starts_with("mrml = "))
            .expect("mrml is a direct dependency");
        assert_eq!(
            dep,
            r#"mrml = { version = "6.0.1", default-features = false, features = ["parse", "render", "css-inline"] }"#
        );
    }

